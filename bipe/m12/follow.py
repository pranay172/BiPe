HISTORY = 128
# A sequence this far behind the last is the Pi restarting its counter (follower.c).
SEQUENCE_RESTART_GAP = 30
TABLE = 8
TWO_PI = 6.28318530717958647692

MODES = ["off", "waiting", "following", "coasting", "braking", "holding"]
EVENTS = ["none", "engaged", "coasting", "lost", "reacquired", "holding", "cancelled"]
REPORTS = ["accepted", "empty", "invalid", "repeated", "wrong_id", "too_old", "gated", "ignored"]


def load():
    return json.loads(CONFIG.read_text())


def config_values(cfg=None):
    """The C configuration struct's fields, in declaration order."""
    cfg = load() if cfg is None else cfg
    tm, cam, est, gate = cfg["timing"], cfg["camera"], cfg["estimator"], cfg["gating"]
    modes, law, lim = cfg["modes"], cfg["law"], cfg["limits"]
    table = est["noise_table"]
    n = len(table["range_m"])
    if n > TABLE:
        raise ValueError("noise table too long")

    def pad(values):
        return [float(v) for v in values] + [0.0] * (TABLE - len(values))

    return {
        "dt": tm["control_dt_s"],
        "history_s": tm["history_s"],
        "max_age_s": tm["max_age_s"],
        "link_delay_s": tm["link_delay_s"],
        "frame_s": tm["frame_s"],
        "camera_ahead_m": cam["ahead_of_axle_m"],
        "camera_ahead_per_lean": cam["ahead_per_lean_m_rad"],
        "process_density": est["process_acceleration_density_m2_s3"],
        "initial_velocity_sigma": est["initial_velocity_sigma_m_s"],
        "table_n": n,
        "table_range": pad(table["range_m"]),
        "table_range_std": pad(table["range_std_m"]),
        "table_bearing_std": pad([math.radians(v) for v in table["bearing_std_deg"]]),
        "noise_scale": est["noise_scale"],
        "range_std_floor": est["range_std_floor_m"],
        "bearing_std_floor": math.radians(est["bearing_std_floor_deg"]),
        "innovation_chi2": gate["innovation_chi2"],
        "gate_m": gate["reacquisition_gate_m"],
        "tag_id": modes["tag_id"],
        "engage_detections": modes["engage_detections"],
        "engage_s": modes["engage_s"],
        "engage_range_min": modes["engage_range_m"][0],
        "engage_range_max": modes["engage_range_m"][1],
        "engage_speed_max": modes["engage_robot_speed_max_m_s"],
        "coast_after_frames": modes["coast_after_frames"],
        "coast_s": modes["coast_s"],
        "stale_s": modes["stale_link_s"],
        "hold_speed": modes["hold_speed_m_s"],
        "nominal_range": law["nominal_range_m"],
        "range_gain": law["range_gain_1_s"],
        "bearing_gain": law["bearing_gain_1_s"],
        "stop_range": law["stop_range_m"],
        "lateral_range_floor": law["lateral_range_floor_m"],
        "speed_max": lim["speed_m_s"],
        "reverse_max": lim["reverse_speed_m_s"],
        "acceleration_max": lim["acceleration_m_s2"],
        "yaw_rate_max": lim["yaw_rate_rad_s"],
        "yaw_acceleration_max": lim["yaw_acceleration_rad_s2"],
        "brake_deceleration": lim["brake_deceleration_m_s2"],
    }


INTEGER_FIELDS = {"table_n", "tag_id", "engage_detections"}


def header_text(cfg=None):
    values = config_values(cfg)
    items = []
    for k, v in values.items():
        if isinstance(v, list):
            text = "{" + ", ".join(repr(float(x)) for x in v) + "}"
        elif k in INTEGER_FIELDS:
            text = f"{int(v)}u"
        else:
            text = repr(float(v))
        items.append(f"    .{k} = {text}, \\")
    digest = hashlib.sha256(CONFIG.read_bytes()).hexdigest() if cfg is None else "custom"
    return (
        "/* Generated by tools/generate_follower_config.py from config/follower-m12.json;\n"
        f"   do not edit. Source sha256 {digest}. */\n"
        "#ifndef BIPE_FOLLOWER_CONFIG_H\n#define BIPE_FOLLOWER_CONFIG_H\n"
        "#define BIPE_FOLLOW_DEFAULT_CONFIG { \\\n" + "\n".join(items) + "\n}\n#endif\n"
    )


def write_header(path=HEADER):
    Path(path).write_text(header_text())
    return path


# Python reference ---------------------------------------------------------------------


def wrap(a):
    return math.remainder(a, TWO_PI)


def _predict(s, P, dt, q):
    s[0] += dt * s[2]
    s[1] += dt * s[3]
    A = [
        P[4 * i + j] + (dt * P[4 * (i + 2) + j] if i < 2 else 0.0)
        for i in range(4)
        for j in range(4)
    ]
    B = [
        A[4 * i + j] + (dt * A[4 * i + j + 2] if j < 2 else 0.0) for i in range(4) for j in range(4)
    ]
    q3, q2, q1 = q * dt * dt * dt / 3.0, q * dt * dt / 2.0, q * dt
    B[0] += q3
    B[5] += q3
    B[2] += q2
    B[8] += q2
    B[7] += q2
    B[13] += q2
    B[10] += q1
    B[15] += q1
    P[:] = B


def _noise(cv, r):
    n = cv["table_n"]
    tr, trs, tbs = cv["table_range"], cv["table_range_std"], cv["table_bearing_std"]
    if r <= tr[0]:
        rs, bs = trs[0], tbs[0]
    elif r >= tr[n - 1]:
        rs, bs = trs[n - 1], tbs[n - 1]
    else:
        i = 0
        while r > tr[i + 1]:
            i += 1
        w = (r - tr[i]) / (tr[i + 1] - tr[i])
        rs = trs[i] + w * (trs[i + 1] - trs[i])
        bs = tbs[i] + w * (tbs[i + 1] - tbs[i])
    rs *= cv["noise_scale"]
    bs *= cv["noise_scale"]
    return (
        max(cv["range_std_floor"], rs),
        max(cv["bearing_std_floor"], bs),
    )


def _measurement(cv, x, y, yaw, ahead, r, b):
    camx = x + ahead * math.cos(yaw)
    camy = y + ahead * math.sin(yaw)
    th = yaw + b
    ct, st = math.cos(th), math.sin(th)
    z = [camx + r * ct, camy + r * st]
    rs, bs = _noise(cv, r)
    vr, vt = rs * rs, (r * bs) * (r * bs)
    r1 = vr * ct * st - vt * ct * st
    R = [vr * ct * ct + vt * st * st, r1, r1, vr * st * st + vt * ct * ct]
    return z, R


def _innovation(s, P, z, R):
    y0, y1 = z[0] - s[0], z[1] - s[1]
    S0, S1, S2, S3 = P[0] + R[0], P[1] + R[1], P[4] + R[2], P[5] + R[3]
    det = S0 * S3 - S1 * S2
    d2 = (y0 * (S3 * y0 - S1 * y1) + y1 * (S0 * y1 - S2 * y0)) / det
    return d2, math.sqrt(y0 * y0 + y1 * y1)


def _update(s, P, z, R):
    y0, y1 = z[0] - s[0], z[1] - s[1]
    S0, S1, S2, S3 = P[0] + R[0], P[1] + R[1], P[4] + R[2], P[5] + R[3]
    det = S0 * S3 - S1 * S2
    I0, I1, I2, I3 = S3 / det, -S1 / det, -S2 / det, S0 / det
    K = [0.0] * 8
    for i in range(4):
        K[2 * i] = P[4 * i] * I0 + P[4 * i + 1] * I2
        K[2 * i + 1] = P[4 * i] * I1 + P[4 * i + 1] * I3
    N = [0.0] * 16
    for i in range(4):
        s[i] += K[2 * i] * y0 + K[2 * i + 1] * y1
        for j in range(4):
            N[4 * i + j] = P[4 * i + j] - (K[2 * i] * P[j] + K[2 * i + 1] * P[4 + j])
    for i in range(4):
        for j in range(4):
            P[4 * i + j] = 0.5 * (N[4 * i + j] + N[4 * j + i])


def _clamp(v, lo, hi):
    return lo if v < lo else (min(v, hi))


def _toward_zero(v, step):
    if abs(v) <= step:
        return 0.0
    return v - step if v > 0 else v + step


class Follower:
    """Python reference of firmware/src/follower.c."""

    def __init__(self, cfg=None):
        self.cv = config_values(cfg)
        self.n = min(round(self.cv["history_s"] / self.cv["dt"]), HISTORY)
        self.mode = 0
        self.requested = self.initialized = self.ticked = False
        self.sequence_seen = self.message_seen = False
        self.s, self.P = [0.0] * 4, [0.0] * 16
        self.history = [None] * HISTORY
        self.head = self.count = 0
        self.last_sequence = self.streak_sequence = 0
        self.streak = 0
        self.streak_start = self.last_range = self.last_fused = 0.0
        self.last_accepted = self.last_message = self.now = 0.0
        self.velocity = self.yaw_rate = self.lost_x = self.lost_y = 0.0
        self.event = self.pending = 0
        self.reports = [0] * 8

    def request(self, on):
        if on:
            if self.mode == 0:
                self.mode = 1
                self.streak = 0
                self.sequence_seen = False
            self.requested = True
        else:
            if self.mode != 0:
                self.pending = EVENTS.index("cancelled")
            self.requested = False
            self.mode = 0
            self.streak = 0
            self.velocity = 0.0
            self.yaw_rate = 0.0

    def _nearest(self, t):
        cv = self.cv
        if self.count == 0:
            return None
        n = self.n
        oldest = (self.head + n + 1 - self.count) % n
        if t < self.history[oldest]["t"] - 0.5 * cv["dt"]:
            return None
        best = self.head
        gap = abs(self.history[self.head]["t"] - t)
        for k in range(1, self.count):
            i = (self.head + n - k) % n
            g = abs(self.history[i]["t"] - t)
            if g < gap:
                gap, best = g, i
            if self.history[i]["t"] < t:
                break
        return best

    def _repropagate(self, k):
        s, P = list(self.history[k]["s"]), list(self.history[k]["P"])
        t = self.history[k]["t"]
        i = k
        while i != self.head:
            i = (i + 1) % self.n
            _predict(s, P, self.history[i]["t"] - t, self.cv["process_density"])
            t = self.history[i]["t"]
            self.history[i]["s"], self.history[i]["P"] = list(s), list(P)
        self.s, self.P = list(s), list(P)

    def _initialize(self, k, z, R):
        h = self.history[k]
        v = self.cv["initial_velocity_sigma"] * self.cv["initial_velocity_sigma"]
        h["s"] = [z[0], z[1], 0.0, 0.0]
        P = [0.0] * 16
        P[0], P[1], P[4], P[5] = R[0], R[1], R[2], R[3]
        P[10] = P[15] = v
        h["P"] = P
        self.initialized = True
        self._repropagate(k)

    def report(self, sequence, tag_id, detected, range_m, bearing_rad, age_s, now):
        cv = self.cv
        if (
            not math.isfinite(now)
            or not math.isfinite(age_s)
            or age_s < 0
            or (
                detected
                and (
                    not math.isfinite(range_m) or not range_m > 0 or not math.isfinite(bearing_rad)
                )
            )
        ):
            self.reports[2] += 1
            return "invalid"
        if (
            self.sequence_seen
            and sequence <= self.last_sequence
            and self.last_sequence - sequence <= SEQUENCE_RESTART_GAP
        ):
            self.reports[3] += 1
            return "repeated"
        self.sequence_seen = True
        self.last_sequence = sequence
        self.message_seen = True
        self.last_message = now
        if self.mode == 0:
            out = "ignored"
        elif not detected:
            self.streak = 0
            out = "empty"
        elif tag_id != cv["tag_id"]:
            self.streak = 0
            out = "wrong_id"
        else:
            t = now - age_s - cv["link_delay_s"]
            k = None if age_s + cv["link_delay_s"] > cv["max_age_s"] else self._nearest(t)
            if k is None:
                out = "too_old"
            else:
                h = self.history[k]
                z, R = _measurement(cv, h["x"], h["y"], h["yaw"], h["ahead"], range_m, bearing_rad)
                d2 = distance = 0.0
                if self.initialized:
                    d2, distance = _innovation(h["s"], h["P"], z, R)
                if self.mode in (1, 5):
                    continues = (
                        self.streak > 0
                        and self.initialized
                        and sequence == self.streak_sequence + 1
                        and distance <= cv["gate_m"]
                    )
                    if continues:
                        _update(h["s"], h["P"], z, R)
                        self._repropagate(k)
                        self.streak += 1
                    else:
                        self._initialize(k, z, R)
                        self.streak = 1
                        self.streak_start = h["t"]
                    self.streak_sequence = sequence
                    self.last_range = range_m
                    self.last_fused = h["t"]
                    self.last_accepted = now
                    out = "accepted"
                else:
                    following = self.mode == 2
                    inside = distance <= cv["gate_m"] or (following and d2 <= cv["innovation_chi2"])
                    if inside:
                        _update(h["s"], h["P"], z, R)
                        self._repropagate(k)
                        self.last_range = range_m
                        self.last_fused = h["t"]
                        self.last_accepted = now
                        if not following:
                            self.mode = 2
                            self.pending = EVENTS.index("reacquired")
                        out = "accepted"
                    else:
                        out = "gated"
        self.reports[REPORTS.index(out)] += 1
        return out

    def _geometry(self, x, y, yaw, ahead):
        camx = x + ahead * math.cos(yaw)
        camy = y + ahead * math.sin(yaw)
        rx, ry = self.s[0] - camx, self.s[1] - camy
        r = math.sqrt(rx * rx + ry * ry)
        d = max(1e-09, r)
        return r, (rx / d, ry / d), wrap(math.atan2(ry, rx) - yaw)

    def estimate(self):
        if not self.initialized or self.count == 0:
            return None
        h = self.history[self.head]
        r, _, b = self._geometry(h["x"], h["y"], h["yaw"], h["ahead"])
        return r, b

    def step(self, now, x, y, yaw, lean, robot_velocity, allowed):
        cv = self.cv
        if not all(math.isfinite(v) for v in (now, x, y, yaw, lean, robot_velocity)) or (
            self.ticked and not now > self.now
        ):
            return None
        dt = now - self.now if self.ticked else cv["dt"]
        self.event = self.pending
        self.pending = 0
        if not allowed and self.mode != 0:
            self.request(False)
            self.event = EVENTS.index("cancelled")
            self.pending = 0
        if not allowed:
            self.requested = False
        if self.initialized and self.ticked:
            _predict(self.s, self.P, dt, cv["process_density"])
        self.head = 0 if self.count == 0 else (self.head + 1) % self.n
        if self.count < self.n:
            self.count += 1
        self.history[self.head] = {
            "t": now,
            "x": x,
            "y": y,
            "yaw": yaw,
            "ahead": cv["camera_ahead_m"] + cv["camera_ahead_per_lean"] * lean,
            "s": list(self.s),
            "P": list(self.P),
        }
        self.now = now
        self.ticked = True
        silent = now - self.last_accepted
        if self.mode in (1, 5):
            if self.streak > 0 and silent > cv["coast_after_frames"] * cv["frame_s"]:
                self.streak = 0
            if (
                self.streak >= cv["engage_detections"]
                and self.last_fused - self.streak_start >= cv["engage_s"] - 1e-9
                and cv["engage_range_min"] <= self.last_range <= cv["engage_range_max"]
                and abs(robot_velocity) < cv["engage_speed_max"]
            ):
                self.mode = 2
                self.event = EVENTS.index("engaged")
        elif self.mode == 2:
            if silent > cv["coast_after_frames"] * cv["frame_s"]:
                self.mode = 3
                self.event = EVENTS.index("coasting")
        if (self.mode == 3 and silent > cv["coast_s"] + 1e-9) or (
            self.mode in (2, 3) and now - self.last_message > cv["stale_s"] + 1e-9
        ):
            self.mode = 4
            self.event = EVENTS.index("lost")
            self.lost_x, self.lost_y = x, y
        v = w = 0.0
        if self.mode in (2, 3):
            r, u, bearing = self._geometry(x, y, yaw, cv["camera_ahead_m"])
            along = self.s[2] * u[0] + self.s[3] * u[1]
            across = -self.s[2] * u[1] + self.s[3] * u[0]
            v = along + cv["range_gain"] * (r - cv["nominal_range"])
            if r < cv["stop_range"]:
                v = 0.0
            floor = cv["lateral_range_floor"]
            w = cv["bearing_gain"] * bearing + across / (max(floor, r))
            v = _clamp(v, -cv["reverse_max"], cv["speed_max"])
            w = _clamp(w, -cv["yaw_rate_max"], cv["yaw_rate_max"])
            a, ya = cv["acceleration_max"] * dt, cv["yaw_acceleration_max"] * dt
            v = self.velocity + _clamp(v - self.velocity, -a, a)
            w = self.yaw_rate + _clamp(w - self.yaw_rate, -ya, ya)
        elif self.mode == 4:
            v = _toward_zero(self.velocity, cv["brake_deceleration"] * dt)
            w = _toward_zero(self.yaw_rate, cv["yaw_acceleration_max"] * dt)
            if v == 0 and w == 0 and abs(robot_velocity) < cv["hold_speed"]:
                self.mode = 5
                self.event = EVENTS.index("holding")
                self.streak = 0
        self.velocity, self.yaw_rate = v, w
        return v, w


