def build_library(directory=BUILD):
    """Compile follower.c with the firmware's warning flags into a cached shared library."""
    identity = hashlib.sha256()
    for path in (SOURCE, API, HEADER):
        identity.update(path.read_bytes())
    directory = Path(directory) / identity.hexdigest()[:16]
    lib = directory / "libbipe_follower.so"
    if not lib.exists():
        directory.mkdir(parents=True, exist_ok=True)
        tmp = directory / f".libbipe_follower.{os.getpid()}.so"
        subprocess.run(
            [
                "gcc",
                "-std=c11",
                "-O2",
                "-Wall",
                "-Wextra",
                "-Werror",
                "-Wconversion",
                "-Wshadow",
                "-fPIC",
                "-shared",
                "-I" + str(ROOT / "firmware/include"),
                str(SOURCE),
                "-lm",
                "-o",
                str(tmp),
            ],
            check=True,
            capture_output=True,
        )
        tmp.replace(lib)  # atomic: parallel workers never load a half-written library
    return lib


_LIBS = {}


def library(path=None):
    path = str(path or build_library())
    if path not in _LIBS:
        lib = c.CDLL(path)
        lib.bipe_follow_default_config.restype = Config
        lib.bipe_follow_config_valid.argtypes = [c.POINTER(Config)]
        lib.bipe_follow_config_valid.restype = c.c_bool
        lib.bipe_follow_init.argtypes = [c.POINTER(State)]
        lib.bipe_follow_init.restype = None
        lib.bipe_follow_request.argtypes = [c.POINTER(State), c.c_bool]
        lib.bipe_follow_request.restype = None
        lib.bipe_follow_report_in.argtypes = [
            c.POINTER(State),
            c.POINTER(Config),
            c.POINTER(Report),
            c.c_double,
        ]
        lib.bipe_follow_report_in.restype = c.c_int
        D = c.c_double
        lib.bipe_follow_step.argtypes = [
            c.POINTER(State),
            c.POINTER(Config),
            D,
            D,
            D,
            D,
            D,
            D,
            c.c_bool,
            c.POINTER(D),
            c.POINTER(D),
        ]
        lib.bipe_follow_step.restype = c.c_bool
        lib.bipe_follow_estimate.argtypes = [
            c.POINTER(State),
            c.POINTER(Config),
            c.POINTER(D),
            c.POINTER(D),
        ]
        lib.bipe_follow_estimate.restype = c.c_bool
        _LIBS[path] = lib
    return _LIBS[path]


def c_config(cfg=None):
    out = Config()
    for k, v in config_values(cfg).items():
        if isinstance(v, list):
            setattr(out, k, (c.c_double * TABLE)(*v))
        elif k in INTEGER_FIELDS:
            setattr(out, k, int(v))
        else:
            setattr(out, k, float(v))
    return out


class CFollower:
    """The firmware follower through ctypes, with the reference's interface."""

    def __init__(self, cfg=None, path=None):
        self.lib = library(path)
        self.config = c_config(cfg)
        if not self.lib.bipe_follow_config_valid(c.byref(self.config)):
            raise ValueError("follower configuration rejected by the firmware")
        self.state = State()
        self.lib.bipe_follow_init(c.byref(self.state))
        self._v, self._w = c.c_double(), c.c_double()

    def request(self, on):
        self.lib.bipe_follow_request(c.byref(self.state), bool(on))

    def report(self, sequence, tag_id, detected, range_m, bearing_rad, age_s, now):
        r = Report(sequence, tag_id, bool(detected), range_m, bearing_rad, age_s)
        return REPORTS[
            self.lib.bipe_follow_report_in(
                c.byref(self.state), c.byref(self.config), c.byref(r), now
            )
        ]

    def step(self, now, x, y, yaw, lean, robot_velocity, allowed):
        ok = self.lib.bipe_follow_step(
            c.byref(self.state),
            c.byref(self.config),
            now,
            x,
            y,
            yaw,
            lean,
            robot_velocity,
            bool(allowed),
            c.byref(self._v),
            c.byref(self._w),
        )
        return (self._v.value, self._w.value) if ok else None

    def estimate(self):
        r, b = c.c_double(), c.c_double()
        if not self.lib.bipe_follow_estimate(
            c.byref(self.state), c.byref(self.config), c.byref(r), c.byref(b)
        ):
            return None
        return r.value, b.value

    @property
    def mode(self):
        return self.state.mode

    @property
    def event(self):
        return self.state.event

    @property
    def s(self):
        return list(self.state.s)

    @property
    def P(self):
        return list(self.state.P)

    @property
    def reports(self):
        return list(self.state.reports)

    @property
    def lost_x(self):
        return self.state.lost_x

    @property
    def lost_y(self):
        return self.state.lost_y
